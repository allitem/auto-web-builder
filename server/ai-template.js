const express = require("express");
const router = express.Router();

/* Mock AI Template Generator */
router.post("/generate", async (req,res)=>{
  const {prompt, modules} = req.body;

  // สร้าง HTML template เบื้องต้น
  let html = `
  <!DOCTYPE html>
  <html>
  <head>
    <title>${prompt}</title>
    <style>
      body{font-family:sans-serif;margin:20px;}
      header{background:#4CAF50;color:white;padding:20px;text-align:center;}
      footer{background:#ddd;color:#333;padding:10px;text-align:center;}
      .content{margin:20px;}
    </style>
  </head>
  <body>
    <header><h1>${prompt}</h1></header>
    <div class="content">
      ${modules.map(m=>`<section><h2>${m.name}</h2><p>Module content here</p></section>`).join("")}
    </div>
    <footer>Generated by AI Auto Web Builder</footer>
  </body>
  </html>
  `;

  res.json({html});
});

module.exports = router;
